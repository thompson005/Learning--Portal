// Builds src/lib/data/tracks/cloudRanges.ts from scripts/cloud-ranges/*.json.
// Refuses to write anything that fails QA, so the app can never ship an unsolvable lab.
//   npx tsx scripts/build-cloud-ranges.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

import { CLOUD_LABS } from "../src/lib/data/tracks/cloudLabs"
import { validateLabPatch, type LabPatch } from "../src/lib/cloud/validate"

const DIR = "scripts/cloud-ranges"
const known = new Set(CLOUD_LABS.map((l) => l.id))
// Optional file names (inside scripts/cloud-ranges) restrict the build; default is every file.
const only = process.argv.slice(2)
const files = only.length
  ? only
  : readdirSync(DIR).filter((f) => f.endsWith(".json")).sort()

const patches: Record<string, LabPatch> = {}
let failures = 0
for (const f of files) {
  const raw = JSON.parse(readFileSync(join(DIR, f), "utf8"))
  for (const p of (Array.isArray(raw) ? raw : [raw]) as LabPatch[]) {
    const errs = validateLabPatch(p, known)
    if (errs.length) {
      failures++
      console.error(`FAIL ${p.labId} (${f})`)
      errs.forEach((e) => console.error("   - " + e))
      continue
    }
    if (patches[p.labId]) {
      failures++
      console.error(`FAIL ${p.labId}: defined twice`)
      continue
    }
    patches[p.labId] = p
  }
}
if (failures) {
  console.error(`\n${failures} lab(s) failed QA — nothing written.`)
  process.exit(1)
}

const missing = CLOUD_LABS.filter((l) => !patches[l.id]).map((l) => l.id)
const out = `import type { Lab } from "@/types"
import type { CloudRange } from "@/types"

// GENERATED by scripts/build-cloud-ranges.ts from scripts/cloud-ranges/*.json.
// Every lab here passed the automated QA (flags reachable, policy tasks solvable).
// Do not edit by hand — edit the JSON and re-run the build.
interface RangePatch {
  title?: string
  objective?: string
  successCriteria?: string[]
  hints?: string[]
  estimatedHours?: number
  resources?: { title: string; url: string; type: "link" | "video" | "platform" | "tool" }[]
  range: CloudRange
}

export const CLOUD_RANGE_PATCHES: Record<string, RangePatch> = ${JSON.stringify(
  Object.fromEntries(
    Object.values(patches).map((p) => [
      p.labId,
      {
        title: p.title,
        objective: p.objective,
        successCriteria: p.successCriteria,
        hints: p.hints,
        estimatedHours: p.estimatedHours,
        resources: p.resources,
        range: p.range,
      },
    ]),
  ),
  null,
  2,
)}

/** Turns the stub cloud labs into full in-browser ranges where a range exists. */
export function applyCloudRanges(labs: Lab[]): Lab[] {
  return labs.map((lab) => {
    const p = CLOUD_RANGE_PATCHES[lab.id]
    if (!p) return lab
    return {
      ...lab,
      platform: "In-browser cloud range (no account needed)",
      title: p.title ?? lab.title,
      objective: p.objective ?? lab.objective,
      successCriteria: p.successCriteria,
      hints: p.hints,
      estimatedHours: p.estimatedHours ?? lab.estimatedHours,
      resources: p.resources ?? lab.resources,
      range: p.range,
    }
  })
}
`
writeFileSync("src/lib/data/tracks/cloudRanges.ts", out)
console.log(`Wrote ${Object.keys(patches).length} ranges to src/lib/data/tracks/cloudRanges.ts`)
if (missing.length) console.log(`Still stub (no range yet): ${missing.join(", ")}`)
